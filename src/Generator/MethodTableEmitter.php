<?php

declare(strict_types=1);

namespace LaraGram\Server\Generator;

use LaraGram\Filesystem\Filesystem;

/**
 * Emits src/Generated/MethodTable.php from the Bot API spec: every
 * documented method, lower-cased as the server matches it, mapped to its
 * handler on {@see \LaraGram\Server\Bot\Client} (`sendMessage` →
 * `processSendMessageQuery`).
 */
final class MethodTableEmitter
{
    public function __construct(private readonly Filesystem $files)
    {
    }

    /**
     * @param array<string, mixed> $spec
     */
    public function emit(array $spec, string $path): void
    {
        $methods = '';
        $names = '';
        foreach ($spec['methods'] as $method) {
            $lower = var_export(strtolower($method['name']), true);
            $methods .= "        {$lower} => ".var_export(self::handlerName($method['name']), true).",\n";
            $names .= "        {$lower} => ".var_export($method['name'], true).",\n";
        }

        $version = var_export((string) $spec['version'], true);

        $this->files->ensureDirectoryExists(dirname($path));
        $this->files->put($path, <<<PHP
<?php

declare(strict_types=1);

namespace LaraGram\Server\Generated;

/**
 * Generated by bin/generate from resources/spec/telegram-api.json. Do not edit.
 */
final class MethodTable
{
    /** Bot API version of the spec. */
    public const VERSION = {$version};

    /** Lower-cased method name => handler on {@see \LaraGram\Server\Bot\Client}. */
    public const METHODS = [
{$methods}    ];

    /** Lower-cased method name => documented spelling. */
    public const NAMES = [
{$names}    ];
}

PHP);
    }

    public static function handlerName(string $method): string
    {
        return 'process'.ucfirst($method).'Query';
    }
}
