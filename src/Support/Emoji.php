    /**
     * td::is_emoji.
     */
    public static function isEmoji(string $str): bool
    {
        $i = strpos(substr($str, 0, self::MAX_EMOJI_LENGTH + 4), "\xE2");
        if ($i === false) {
            return self::isEmojiElement($str);
        }

        $start = 0;
        $length = strlen($str);
        for (; $i + 3 < $length; $i++) {
            if ($str[$i] === "\xE2" && $str[$i + 1] === "\x80" && $str[$i + 2] === "\x8D") {
                if (!self::isEmojiElement(substr($str, $start, $i - $start))) {
                    return false;
                }
                $start = $i + 3;
                $i += 2;
            }
        }

        return self::isEmojiElement(substr($str, $start));
    }

    private static function isEmojiElement(string $str): bool
    {
        $length = strlen($str);
        if ($length > self::MAX_EMOJI_LENGTH + 3) {
            return false;
        }
        if (isset(self::ELEMENTS[$str])) {
            return true;
        }
        if ($length <= 3 || substr($str, -3) !== "\xEF\xB8\x8F") {
            return false;
        }
        if ($length >= 6 && substr($str, -6, 3) === "\xEF\xB8\x8F") {
            return false;
        }

        return isset(self::ELEMENTS[substr($str, 0, -3)]);
    }
